import { describe, expect, it } from 'vitest';
import { cagr, ratios, valueCompany, valuationReadiness } from '../../src/lib/finance';
import { sampleAssumptions, sampleDataset } from '../../src/lib/sample';
import { statementIssues } from '../../src/lib/statement-checks';
import { applySourceReview } from '../../src/lib/review';
import { normalizedFixture } from '../fixtures/financials';
import { runResearch } from '../../src/lib/research';
import { research } from '../../server/research-service';
import { parseSession, serializeSession } from '../../src/lib/session';
import type { Assumptions } from '../../src/lib/types';

const latest = sampleDataset.years.at(-1)!;
const previous = sampleDataset.years.at(-2)!;
const note =
  'Teaching assumptions: growth 5%, operating margin 20%, tax 25%, WACC 10%; no extra claims.';
const sourceReview = {
  confirmed: true,
  notes: 'Checked original statement dates, units and definitions.',
  overrides: [],
};
const scope = {
  valuationConfirmed: true,
  valuationNotes:
    'Synthetic fixture: no preferred/NCI or leases; debt and operating NWC reconciled.',
};

// Values are worked independently, not generated by the production formulas.
describe('independent finance audit', () => {
  it('matches all twelve ratios to a hand-worked statement', () => {
    const row = {
      ...latest,
      revenue: 1000,
      grossProfit: 600,
      ebit: 200,
      netIncome: 120,
      depreciation: 50,
      capex: 80,
      cashFromOperations: 180,
      cash: 100,
      shortTermInvestments: 50,
      receivables: 150,
      currentAssets: 500,
      currentLiabilities: 250,
      debt: 400,
      equity: 800,
      totalAssets: 2000,
      interestExpense: 25,
    };
    const opening = { ...previous, equity: 700, totalAssets: 1800 };
    const expected: Record<string, number> = {
      grossMargin: 0.6,
      operatingMargin: 0.2,
      netMargin: 0.12,
      currentRatio: 2,
      quickRatio: 1.2,
      debtEquity: 0.5,
      netDebtEbitda: 1,
      interestCoverage: 8,
      roe: 0.16,
      roa: 120 / 1900,
      cashConversion: 1.5,
      cashAfterCapex: 100,
    };
    for (const metric of ratios(row, opening))
      expect(metric.value, metric.id).toBeCloseTo(expected[metric.id], 12);
  });
  it('requires adjoining annual dates and compatible units for average-balance returns', () => {
    for (const opening of [
      { ...previous, periodEnd: '2024-12-30' },
      { ...previous, currency: 'EUR' as 'USD' },
    ])
      expect(ratios(latest, opening).find((m) => m.id === 'roa')!.value).toBeNull();
    expect(
      ratios({ ...latest, netIncome: -50 }, previous).find((m) => m.id === 'roe')!.value,
    ).toBeLessThan(0);
    expect(
      ratios({ ...latest, netIncome: -50 }, previous).find((m) => m.id === 'cashConversion')!.value,
    ).toBeNull();
  });
  it('never emits infinite ratios or invalid CAGR', () => {
    expect(
      ratios({ ...latest, netIncome: 1e308, revenue: 1e-308 }).find((m) => m.id === 'netMargin')!
        .value,
    ).toBeNull();
    for (const intervals of [NaN, Infinity, 1.5, -1]) expect(cagr(100, 120, intervals)).toBeNull();
    expect(cagr(1e-300, 1e300, 10)).toBeCloseTo(1e60, -48);
  });
  it('matches a growing perpetuity including tax, D&A, CapEx and working capital', () => {
    const row = { ...latest, revenue: 1000, ebit: 200, operatingNwc: 100, cash: 50 };
    const a: Assumptions = {
      growth: 0.05,
      margin: 0.2,
      taxRate: 0.25,
      daRate: 0.04,
      capexRate: 0.06,
      nwcRate: 0.1,
      wacc: 0.1,
      terminalGrowth: 0.05,
      excessCash: 20,
      debt: 300,
      nonOperatingAssets: 10,
      otherClaims: 30,
      shares: 100,
    };
    const result = valueCompany(row, a);
    // First-year FCFF: 157.5 + 42 - 63 - 5 = 131.5. Constant 5% growth thereafter.
    expect(result.forecast[0].fcff).toBeCloseTo(131.5, 10);
    expect(result.enterpriseValue).toBeCloseTo(2630, 8);
    expect(result.equityValue).toBeCloseTo(2330, 8);
    expect(result.perShare).toBeCloseTo(23.3, 10);
    expect(result.pvForecast + result.pvTerminal).toBeCloseTo(2630, 8);
  });
  it('independently discounts five forecast cash flows and year-six terminal cash flow', () => {
    const row = { ...latest, revenue: 1000, ebit: 200, operatingNwc: 100 };
    const a = {
      ...sampleAssumptions,
      growth: 0.1,
      margin: 0.2,
      taxRate: 0.25,
      daRate: 0.03,
      capexRate: 0.07,
      nwcRate: 0.1,
      wacc: 0.1,
      terminalGrowth: 0.02,
      excessCash: 0,
      debt: 0,
    };
    const r = valueCompany(row, a);
    const flows = [111, 122.1, 134.31, 147.741, 162.5151];
    flows.forEach((flow, i) => expect(r.forecast[i].fcff).toBeCloseTo(flow, 9));
    // Year six: revenue1642.7202; NOPAT246.40803 + DA49.281606 - capex114.990414 - deltaNWC3.22102.
    expect(r.terminal.fcff).toBeCloseTo(177.478202, 9);
    const ev =
      flows.reduce((sum, v, i) => sum + v / 1.1 ** (i + 1), 0) + 177.478202 / 0.08 / 1.1 ** 5;
    expect(r.enterpriseValue).toBeCloseTo(ev, 8);
  });
  it('handles negative operating working capital without reversing its cash-flow sign', () => {
    const row = { ...latest, revenue: 1000, ebit: 200, operatingNwc: -100 };
    const r = valueCompany(row, {
      ...sampleAssumptions,
      growth: 0.1,
      nwcRate: -0.1,
      capexRate: 0.07,
    });
    expect(r.forecast[0].deltaNwc).toBeCloseTo(-10, 10);
    expect(r.forecast[0].fcff).toBeCloseTo(
      r.forecast[0].nopat + r.forecast[0].depreciation - r.forecast[0].capex + 10,
      10,
    );
  });
  it('rejects perpetual asset liquidation, unknown excess cash and nonfinite per-share results', () => {
    expect(() =>
      valueCompany(latest, {
        ...sampleAssumptions,
        terminalGrowth: 0,
        capexRate: 0,
        daRate: 0.04,
        nwcRate: 0,
      }),
    ).toThrow(/reinvestment/);
    expect(() =>
      valueCompany({ ...latest, cash: null }, { ...sampleAssumptions, excessCash: 1 }),
    ).toThrow(/cash/);
    expect(() => valueCompany(latest, { ...sampleAssumptions, shares: 1e-320 })).toThrow(
      /overflow/,
    );
  });
  it('preserves unit scaling and economic sensitivities across a deterministic grid', () => {
    for (const growth of [0, 0.05, 0.15])
      for (const wacc of [0.08, 0.1, 0.14]) {
        const a = { ...sampleAssumptions, growth, wacc };
        const base = valueCompany(latest, a);
        const scaled = valueCompany(
          {
            ...latest,
            revenue: latest.revenue! * 3,
            ebit: latest.ebit! * 3,
            operatingNwc: latest.operatingNwc! * 3,
            cash: latest.cash! * 3,
          },
          {
            ...a,
            excessCash: a.excessCash * 3,
            debt: a.debt * 3,
            nonOperatingAssets: a.nonOperatingAssets * 3,
            otherClaims: a.otherClaims * 3,
            shares: a.shares! * 3,
          },
        );
        expect(scaled.enterpriseValue).toBeCloseTo(base.enterpriseValue * 3, 7);
        expect(scaled.perShare).toBeCloseTo(base.perShare!, 10);
        expect(valueCompany(latest, { ...a, wacc: wacc + 0.01 }).enterpriseValue).toBeLessThan(
          base.enterpriseValue,
        );
        expect(
          valueCompany(latest, { ...a, capexRate: a.capexRate + 0.01 }).enterpriseValue,
        ).toBeLessThan(base.enterpriseValue);
      }
  });
});

describe('statement and valuation approval boundaries', () => {
  it('rejects overlapping liquidity balances and current totals above consolidated totals', () => {
    expect(
      statementIssues({
        ...latest,
        currentAssets: 100,
        cash: 60,
        shortTermInvestments: 30,
        receivables: 40,
      }).join(' '),
    ).toMatch(/receivables exceed/);
    expect(
      statementIssues({ ...latest, currentAssets: latest.totalAssets! + 100 }).join(' '),
    ).toMatch(/Current assets exceed/);
    expect(
      statementIssues({ ...latest, currentLiabilities: latest.totalLiabilities! + 100 }).join(' '),
    ).toMatch(/Current liabilities exceed/);
  });
  it('allows historical review without approving DCF, and cannot bypass this through direct workers', async () => {
    const { dataset } = await normalizedFixture();
    const reviewed = applySourceReview(dataset, sourceReview);
    expect(reviewed.sec!.review!.valuationConfirmed).toBe(false);
    const run = await runResearch(
      reviewed,
      { ...sampleAssumptions, shares: null },
      true,
      undefined,
      note,
    );
    expect(run.agents[1].evidence.find((m) => m.id === 'ratio:operatingMargin')!.value).toBe(0.2);
    expect(run.agents[2].evidence[0].text).toMatch(/suitability/);
  });
  it('rechecks manual statements and removes cleared mappings rather than retaining stale values', async () => {
    const { dataset } = await normalizedFixture();
    const overrides = [
      {
        id: 'FY2025:equity',
        value: 1200,
        reason: 'No preferred or non-controlling equity in the fixture.',
      },
    ];
    const accepted = applySourceReview(dataset, { ...sourceReview, ...scope, overrides });
    expect(accepted.years.at(-1)!.equity).toBe(1200);
    expect(() =>
      applySourceReview(dataset, {
        ...sourceReview,
        ...scope,
        overrides: [{ ...overrides[0], value: 100 }],
      }),
    ).toThrow(/reconcile/);
    const cleared = applySourceReview(accepted, sourceReview);
    expect(cleared.years.at(-1)!.equity).toBeNull();
    expect(cleared.sec!.evidence['FY2025:equity'].status).toBe('missing');
  });
  it('requires baseline investment/debt evidence, scope and rationale even when assumptions are numeric', async () => {
    const { dataset, service } = await normalizedFixture();
    const approved = applySourceReview(dataset, { ...sourceReview, ...scope });
    expect(valuationReadiness(approved, sampleAssumptions)).toMatch(/capitalization/);
    expect(valuationReadiness(approved, { ...sampleAssumptions, shares: null })).toMatch(
      /operatingNwc, debt/,
    );
    const complete = {
      ...sourceReview,
      ...scope,
      overrides: [
        {
          id: 'FY2025:operatingNwc',
          value: 100,
          reason: 'Fixture operating assets less operating liabilities.',
        },
        {
          id: 'FY2025:debt',
          value: 300,
          reason: 'Fixture total current and non-current borrowing.',
        },
      ],
    };
    const request = {
      source: {
        kind: 'sec',
        cik: dataset.sec!.cik,
        years: 5,
        sha256: dataset.sourceHash,
        review: complete,
      },
      assumptions: { ...sampleAssumptions, shares: null, excessCash: 0 },
      approved: true,
      assumptionNotes: note,
    };
    const result = await research(service, request);
    expect(result.agents[2].evidence.find((e) => e.id === 'dcf:Base')!.value).toBeGreaterThan(0);
    const withoutRationale = await research(service, { ...request, assumptionNotes: '' });
    expect(withoutRationale.agents[2].evidence[0].text).toMatch(/rationale/);
    const restored = parseSession(
      serializeSession(applySourceReview(dataset, complete), request.assumptions, 5, 'Base', note),
    );
    expect(restored.assumptionNotes).toBe(note);
    expect(valuationReadiness(restored.dataset, restored.assumptions)).toMatch(/snapshot/);
    expect(
      (await runResearch(restored.dataset, restored.assumptions, true, undefined, note)).agents[2]
        .evidence[0].text,
    ).toMatch(/snapshot/);
  });
});
